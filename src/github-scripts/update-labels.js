/**
 * @file Updates issue labels after parsing and validating a theme request.
 */

const {
  APPROVE_QUEUE_LABEL,
  APPROVE_THEME_LABEL
} = require('./approval-queue.js')
const {issueParams, labelNames, repoParams} = require('./github-issue.js')

const METADATA_LABEL_COLORS = {
  type: '1d76db',
  country: '0e8a16',
  rating: '5319e7'
}

/**
 * Add or remove a label name from an in-memory label list.
 *
 * @param {string[]} currentLabels Mutable list of current label names.
 * @param {string} labelName Label name to add or remove.
 * @param {boolean} enabled Whether the label should be present.
 * @returns {void}
 */
function setLabelState(currentLabels, labelName, enabled) {
  const labelExists = currentLabels.includes(labelName)

  if (!labelExists && enabled) {
    currentLabels.push(labelName)
  } else if (labelExists && !enabled) {
    const index = currentLabels.indexOf(labelName)
    currentLabels.splice(index, 1)
  }
}

/**
 * Create a repository label if it is missing.
 *
 * @param {object} options Options for creating a repository label.
 * @param {object} options.github Authenticated Octokit client.
 * @param {import('./github-issue.js').GitHubScriptContext} options.context The actions/github-script context object.
 * @param {string} options.name GitHub label name generated by the updater.
 * @returns {Promise<void>} Promise resolved when the repository label exists.
 */
async function ensureMetadataLabel({github, context, name}) {
  const params = {...repoParams(context), name}
  try {
    await github.rest.issues.getLabel(params)
    return
  } catch (error) {
    if (error.status !== 404) {
      throw error
    }
  }

  try {
    await github.rest.issues.createLabel({
      ...params,
      color: METADATA_LABEL_COLORS[name.split(':', 1)[0]]
    })
  } catch (error) {
    if (error.status !== 422) {
      throw error
    }
    // Another request can create the same repository label between lookup and creation.
    await github.rest.issues.getLabel(params)
  }
}

/**
 * Update labels after issue validation and return whether approval should continue.
 *
 * @param {object} options Options supplied by actions/github-script.
 * @param {object} options.github Authenticated Octokit client from actions/github-script.
 * @param {import('./github-issue.js').GitHubScriptContext} options.context The actions/github-script context object.
 * @returns {Promise<string|undefined>} "true" when the approval workflow should continue.
 */
async function run({github, context}) {
  const labels = await github.rest.issues.listLabelsOnIssue({...issueParams(context), per_page: 100})
  const anime = process.env.ANIME
  const autoClose = process.env.AUTO_CLOSE
  const exception = process.env.EXCEPTION
  const duplicate = process.env.DUPLICATE

  let currentLabels = labelNames(labels)
  if (process.env.METADATA_LABELS) {
    const metadataLabels = JSON.parse(process.env.METADATA_LABELS)
    for (const name of metadataLabels) {
      if (!currentLabels.includes(name)) {
        await ensureMetadataLabel({github, context, name}) // NOSONAR javascript:S9382: Serialize GitHub label creation.
      }
    }
    currentLabels = currentLabels.filter(name => !/^(type|country|rating):/i.test(name))
    currentLabels.push(...metadataLabels)
  }


  setLabelState(currentLabels, 'exception', exception === 'true')
  setLabelState(currentLabels, 'duplicate', duplicate === 'true')
  if (anime === 'true') {
    setLabelState(currentLabels, 'anime', true)
  }

  const labelAdd = currentLabels.includes(APPROVE_THEME_LABEL)

  if (labelAdd && (autoClose === 'true' || exception === 'true')) {
    setLabelState(currentLabels, APPROVE_THEME_LABEL, false)
  }

  setLabelState(currentLabels, APPROVE_QUEUE_LABEL, false)

  await github.rest.issues.setLabels({
    ...issueParams(context),
    labels: currentLabels
  })

  if (labelAdd && autoClose !== 'true' && exception !== 'true') {
    return 'true'
  }
}

module.exports = {
  run,
  setLabelState
}
